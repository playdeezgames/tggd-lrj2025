#!/usr/bin/env python3
"""Generates odin/game/font_data.odin from odin/assets/*.ttf and odin/game/sprite_data.odin from the CC0 sprite sheets.

Needs Pillow. Fonts are rendered at 16 px without anti-aliasing (the size their designer drew them for), one u16 row
bitmask per pixel row (bit x = pixel x), with the advance each glyph's designer set (ink plus spacing).
Sprites are 10 by 10, one u16 row bitmask each. The two sprites marked HAND are drawn here, not taken from a sheet."""
import os
from PIL import Image, ImageDraw, ImageFont

root = os.path.join(os.path.dirname(__file__), "..", "..")
def path(*p): return os.path.join(root, *p)

# ---- text fonts: (Font_Id member, ttf, rows above the baseline, rows below) ----
FONTS = [("Small", "odin/assets/m3x6.ttf", 6, 2), ("Text", "odin/assets/m5x7.ttf", 7, 2)]
FIRST, LAST = 32, 126

def bits_to_hex(bits): return f"0x{bits:04X}"

out = ["package game", "", "// GENERATED by tools/gen/gen_assets.py (fonts: m3x6 and m5x7 by Daniel Linssen, see odin/assets/README.md). Do not edit.", "",
       "Font_Id :: enum u8 {"]
out += [f"\t{n}," for n, *_ in FONTS] + ["\tSprites,", "}", ""]
tables = []
fonts_entries = []
for name, ttf, above, below in FONTS:
    font = ImageFont.truetype(path(ttf), 16)
    height = above + below
    advances, rows = [], []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        advance = int(font.getlength(ch))
        img = Image.new("L", (max(advance, 1) + 4, height), 0)
        d = ImageDraw.Draw(img); d.fontmode = "1"
        d.text((0, above), ch, font=font, fill=255, anchor="ls")
        glyph_rows = []
        for y in range(height):
            b = 0
            for x in range(img.width):
                if img.getpixel((x, y)) > 127:
                    assert x < 16, (name, ch, x)
                    b |= 1 << x
            glyph_rows.append(b)
        advances.append(advance); rows.extend(glyph_rows)
    space = advances[0]
    n = LAST - FIRST + 1
    tables.append(f"FONT_ADVANCE_{name.upper()} := [{n}]u8 {{" + ", ".join(map(str, advances)) + "}")
    tables.append(f"FONT_ROWS_{name.upper()} := [{n * height}]u16 {{")
    for g in range(n):
        tables.append("\t" + ", ".join(bits_to_hex(b) for b in rows[g * height:(g + 1) * height]) + f", // {FIRST + g} {chr(FIRST + g)!r}")
    tables.append("}")
    fonts_entries.append(f"\t.{name} = {{height = {height}, first = {FIRST}, count = {n}, space = {space}, advance = FONT_ADVANCE_{name.upper()}[:], rows = FONT_ROWS_{name.upper()}[:]}},")

# ---- sprites ----
SHEETS = {"people": "Bit-Bonanza-10x10-v-5.0/1-Bit/People.png", "creatures": "Bit-Bonanza-10x10-v-5.0/1-Bit/Creatures.png",
          "weapons": "Bit-Bonanza-10x10-v-5.0/1-Bit/Weapons.png", "tools": "Bit-Bonanza-10x10-v-5.0/1-Bit/Tools.png",
          "potions": "Bit-Bonanza-10x10-v-5.0/1-Bit/Potions.png", "food": "Bit-Bonanza-10x10-v-5.0/1-Bit/Food.png",
          "civilized": "Bountiful-Bits-10x10-v-3.1/1-Bit/Civilized.png"}
HAND_FLOOR = ["..........", "...#......", "..........", "......#...", ".#........", "..........", ".......#..", "....#.....", "..........", "#.....#..."]
HAND_THREAT = ["..........", "....##....", "...####...", "...####...", "...####...", "....##....", "....##....", "..........", "....##....", "....##...."]
# Odin enum member, number (the original's Chr(n), kept so the ported tables read the same), source
SPRITES = [("Blank", 0, None), ("Player", 1, ("people", 0, 0)), ("Wall", 2, ("civilized", 20, 1)), ("Floor", 3, "HAND_FLOOR"),
           ("Door", 4, ("civilized", 17, 2)), ("Key", 5, ("tools", 0, 6)), ("Sign", 6, ("civilized", 12, 3)),
           ("Food", 7, ("food", 4, 0)), ("Moon_Person", 8, ("creatures", 3, 6)), ("Sword", 9, ("weapons", 0, 0)),
           ("Shield", 10, ("weapons", 0, 7)), ("Potion", 11, ("potions", 0, 0)), ("Threat", 12, "HAND_THREAT")]
assert [s[1] for s in SPRITES] == list(range(len(SPRITES)))
images = {k: Image.open(path(v)).convert("L") for k, v in SHEETS.items()}
def sprite_rows(src):
    if src is None: return [0] * 10
    if isinstance(src, str):
        pic = HAND_FLOOR if src == "HAND_FLOOR" else HAND_THREAT
        return [sum(1 << x for x, c in enumerate(row) if c == "#") for row in pic]
    sheet, col, row = src
    tile = images[sheet].crop((col * 10, row * 10, col * 10 + 10, row * 10 + 10))
    return [sum(1 << x for x in range(10) if tile.getpixel((x, y)) > 127) for y in range(10)]

tables.append(f"FONT_ADVANCE_SPRITES := [{len(SPRITES)}]u8 {{" + ", ".join(["10"] * len(SPRITES)) + "}")
tables.append(f"FONT_ROWS_SPRITES := [{len(SPRITES) * 10}]u16 {{")
for name, number, src in SPRITES:
    tables.append("\t" + ", ".join(bits_to_hex(b) for b in sprite_rows(src)) + f", // {number} {name}")
tables.append("}")
fonts_entries.append(f"\t.Sprites = {{height = 10, first = 0, count = {len(SPRITES)}, space = 10, advance = FONT_ADVANCE_SPRITES[:], rows = FONT_ROWS_SPRITES[:]}},")

out += ["FONTS := [Font_Id]Font {"] + fonts_entries + ["}", ""]
out += ["// Sprite numbers are the original's Chr(n) glyphs, so ported tables read the same.", "Sprite :: enum u8 {"]
out += [f"\t{n} = {num}," for n, num, _ in SPRITES] + ["}", ""]
out += ["// Advance widths are in FONT_ADVANCE_*; each glyph's rows follow; one u16 per row, bit x is the pixel in column x."]
out += tables
open(path("odin/game/font_data.odin"), "w").write("\n".join(out) + "\n")
print("wrote odin/game/font_data.odin")
